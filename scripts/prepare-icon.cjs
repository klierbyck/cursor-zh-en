const { app, nativeImage } = require('electron')
const { mkdir, writeFile } = require('node:fs/promises')
const { resolve } = require('node:path')

app.whenReady().then(async () => {
  const source = nativeImage.createFromPath(resolve('src/renderer/icon.png'))
  if (source.isEmpty()) throw new Error('icon.png 无法读取')
  await mkdir(resolve('out'), { recursive: true })
  const png = source.resize({ width: 256, height: 256 }).toPNG()
  const header = Buffer.alloc(22)
  header.writeUInt16LE(1, 2)
  header.writeUInt16LE(1, 4)
  header.writeUInt16LE(1, 10)
  header.writeUInt16LE(32, 12)
  header.writeUInt32LE(png.length, 14)
  header.writeUInt32LE(22, 18)
  await writeFile(resolve('out/app-icon.ico'), Buffer.concat([header, png]))
  await writeFile(resolve('out/icon.png'), source.resize({ width: 1024, height: 1024 }).toPNG())
  console.log('应用图标已从 icon.png 生成')
  app.quit()
}).catch(error => { console.error(error); app.exit(1) })
